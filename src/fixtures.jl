# Explain fixtures with golden outputs (milestone M2).
#
# A fixture is the reference with exactly one hole replaced by a buggy body
# (projects/<p>/fixtures.toml). Running explain on it must (a) name the
# expected hole (or JT000) in "Start here" and (b) produce exactly the committed
# golden text. (a) is the behavioural claim; (b) catches any unreviewed change
# to explain's wording, ranking or measurements.
#
# The golden text is deterministic because explain's `text` contains no clocks
# (timings are returned separately), no absolute paths, sorted findings, and
# measurements taken single-threaded after warm-up on the pinned Julia. JET is
# not run for goldens (it is opt-in and slow).

module Fixtures

using TOML
using ..Scaffold, ..HoleMap, ..Explain

export Fixture, load_fixtures, validate_fixtures, run_fixture, golden_path, compute_goldens

struct Fixture
    name::String
    hole::String
    stage::Int
    expect_start::String
    misconception::String
    description::String
    body::String
end

fixtures_path(p::Scaffold.ProjectSpec) = joinpath(p.dir, "fixtures.toml")
golden_path(p::Scaffold.ProjectSpec, f::Fixture) = joinpath(p.dir, "fixtures", f.name * ".golden.txt")

function load_fixtures(p::Scaffold.ProjectSpec)
    isfile(fixtures_path(p)) || return Fixture[]
    d = TOML.parsefile(fixtures_path(p))
    return [Fixture(x["name"], x["hole"], x["stage"], x["expect_start"], x["misconception"],
                    x["description"], x["body"]) for x in d["fixture"]]
end

"""Structural problems (no Julia run needed): every hole has a fixture, etc."""
function validate_fixtures(p::Scaffold.ProjectSpec, fx::Vector{Fixture})
    problems = String[]
    ids = Dict(h.id => h for h in p.holes)
    allunique(f.name for f in fx) || push!(problems, "fixture names are not unique")
    for f in fx
        occursin(r"^[a-z0-9_-]+$", f.name) || push!(problems, "fixture `$(f.name)`: name must be [a-z0-9_-]")
        h = get(ids, f.hole, nothing)
        h === nothing && (push!(problems, "fixture `$(f.name)`: unknown hole `$(f.hole)`"); continue)
        f.stage in p.stages && f.stage >= h.stage ||
            push!(problems, "fixture `$(f.name)`: stage $(f.stage) does not open hole `$(f.hole)` (stage $(h.stage))")
        f.expect_start in (f.hole, "JT000") ||
            push!(problems, "fixture `$(f.name)`: expect_start must be its hole or JT000")
        isempty(strip(f.misconception)) && push!(problems, "fixture `$(f.name)`: no misconception")
        occursin("TODO(hole:", f.body) && push!(problems, "fixture `$(f.name)`: body is the TODO body")
    end
    for h in p.holes
        any(f -> f.hole == h.id && f.expect_start == h.id, fx) ||
            push!(problems, "hole `$(h.id)` has no fixture whose explain must point at it")
    end
    return problems
end

"""Materialise a fixture as a student working directory (caller removes it)."""
function materialize(p::Scaffold.ProjectSpec, f::Fixture)
    dir = HoleMap.materialize(p, Dict(f.hole => f.body))
    write(joinpath(dir, ".tutor-project.toml"),
          "# generated by tutor fixtures\nproject = \"$(p.name)\"\nstage = $(f.stage)\n")
    return dir
end

"""
    run_fixture(p, f) -> (text, problems)

Run explain on the fixture; `problems` lists violated behavioural claims.
"""
function run_fixture(p::Scaffold.ProjectSpec, f::Fixture)
    dir = materialize(p, f)
    r = try
        Explain.explain(p, dir; hints = 1, run_measurements = true, jet = false)
    finally
        rm(dir; recursive = true, force = true)
    end
    problems = String[]
    start = something(findfirst(l -> startswith(l, "Start here:"), split(r.text, '\n')), 0)
    line = start == 0 ? "" : split(r.text, '\n')[start]
    want = f.expect_start == "JT000" ? "the file does not parse" : "Start here: hole `$(f.expect_start)`"
    occursin(want, line) ||
        push!(problems, "fixture `$(f.name)`: Start here should name $(f.expect_start), got: $(isempty(line) ? "(none)" : line)")
    r.exitcode == 1 || push!(problems, "fixture `$(f.name)`: explain exit code $(r.exitcode), expected 1")
    # Separator-agnostic: drop every `/` and `\` before comparing, so raw,
    # `\\`-escaped and forward-slash spellings of a path are all caught.
    flat(s) = filter(c -> c != '/' && c != '\\', s)
    for bad in (dir, tempdir(), homedir())
        occursin(flat(bad), flat(r.text)) &&
            push!(problems, "fixture `$(f.name)`: output contains a machine path ($(basename(bad)))")
    end
    return r.text, problems
end

"""Run every fixture (4 at a time; each run is its own processes). Returns name => (text, problems)."""
function compute_goldens(p::Scaffold.ProjectSpec, fx::Vector{Fixture}; ntasks::Int = 4, log = stdout)
    results = asyncmap(fx; ntasks) do f
        out = run_fixture(p, f)
        println(log, "  ran fixture ", f.name, isempty(out[2]) ? "" : "  ($(length(out[2])) problem(s))")
        out
    end
    return Dict(f.name => r for (f, r) in zip(fx, results))
end

end # module Fixtures
